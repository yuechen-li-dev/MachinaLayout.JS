import { UnserializableValueError } from "../iter/effects";
import { Text } from "../text/utilities";

/**
 * Plain-data-to-TypeScript-literal emitter. Accepts what JSON accepts plus
 * `undefined` object fields (omitted) — never functions, class instances,
 * symbols, non-finite numbers, or cycles. Key order is preserved (it is
 * meaningful, e.g. concept field order); determinism is enforced elsewhere.
 */
export function toTsLiteral(
  value: unknown,
  indent = 0,
  path = "",
  seen = new Set<object>(),
): string {
  const pad = "  ".repeat(indent);
  const inner = "  ".repeat(indent + 1);
  if (value === null) return "null";
  switch (typeof value) {
    case "string":
      return JSON.stringify(value);
    case "boolean":
      return String(value);
    case "number":
      if (!Number.isFinite(value)) {
        throw new UnserializableValueError(path, `${value} cannot be emitted as a literal`);
      }
      return Object.is(value, -0) ? "0" : String(value);
    case "undefined":
      throw new UnserializableValueError(
        path,
        "undefined cannot be emitted (omit the field or use null)",
      );
    case "object": {
      if (seen.has(value)) {
        throw new UnserializableValueError(path, "cycle");
      }
      seen.add(value);
      try {
        if (Array.isArray(value)) {
          if (value.length === 0) return "[]";
          const items = value.map((item, index) =>
            toTsLiteral(item, indent + 1, `${path}[${index}]`, seen),
          );
          return `[\n${items.map((item) => `${inner}${item},`).join("\n")}\n${pad}]`;
        }
        const prototype = Object.getPrototypeOf(value);
        if (prototype !== Object.prototype && prototype !== null) {
          throw new UnserializableValueError(
            path,
            `${prototype?.constructor?.name ?? "class instance"} is not plain data`,
          );
        }
        const entries = Object.entries(value).filter(([, item]) => item !== undefined);
        if (entries.length === 0) return "{}";
        const lines = entries.map(([key, item]) => {
          const name = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
          return `${inner}${name}: ${toTsLiteral(item, indent + 1, path ? `${path}.${key}` : key, seen)},`;
        });
        return `{\n${lines.join("\n")}\n${pad}}`;
      } finally {
        seen.delete(value);
      }
    }
    default:
      throw new UnserializableValueError(path, `${typeof value} is not plain data`);
  }
}

export type TsTypeRef = {
  /** Type name to `satisfies` (and import). */
  readonly type: string;
  /** Module to import the type from (type-only import). */
  readonly from: string;
};

export type TsDeclaration = {
  readonly kind: "tsExportConst";
  readonly name: string;
  readonly value: unknown;
  readonly satisfies?: TsTypeRef;
  readonly description?: string;
};

/** `export const <name> = <literal> as const [satisfies <Type>];` */
export function exportConst(
  name: string,
  value: unknown,
  options: { readonly satisfies?: TsTypeRef; readonly description?: string } = {},
): TsDeclaration {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) {
    throw new Error(`'${name}' is not a valid export name.`);
  }
  return { kind: "tsExportConst", name, value, ...options };
}

export function renderTsModule(
  artifactPath: string,
  declarations: readonly TsDeclaration[],
): string {
  const names = new Set<string>();
  for (const declaration of declarations) {
    if (names.has(declaration.name)) {
      throw new Error(`Duplicate export '${declaration.name}' in ${artifactPath}.`);
    }
    names.add(declaration.name);
  }

  const imports = new Map<string, Set<string>>();
  for (const declaration of declarations) {
    if (declaration.satisfies) {
      const set = imports.get(declaration.satisfies.from) ?? new Set<string>();
      set.add(declaration.satisfies.type);
      imports.set(declaration.satisfies.from, set);
    }
  }

  const sortedImports = [...imports].sort(([a], [b]) => a.localeCompare(b));
  const text = Text.lines(
    `// Generated by machinalayout/comptime from artifact "${artifactPath}". Do not edit: change the generator and re-run CT.write.`,
    sortedImports.length > 0 && [
      Text.blank,
      sortedImports.map(
        ([from, types]) =>
          `import type { ${[...types].sort().join(", ")} } from ${JSON.stringify(from)};`,
      ),
    ],
    declarations.map((declaration) => {
      const literal = toTsLiteral(declaration.value, 0, declaration.name);
      const satisfies = declaration.satisfies ? ` satisfies ${declaration.satisfies.type}` : "";
      return [
        Text.blank,
        declaration.description && `/** ${declaration.description.replace(/\*\//g, "*\\/")} */`,
        `export const ${declaration.name} = ${literal} as const${satisfies};`,
      ];
    }),
  );
  return `${text}\n`;
}
